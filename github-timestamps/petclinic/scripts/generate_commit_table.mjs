#!/usr/bin/env node
/* Audit pinned upstream Git-blame replay, emit an actual SHA-linked commit table. */
import assert from "node:assert/strict";
import {readFileSync,writeFileSync} from "node:fs";
const base="github-timestamps/petclinic/";
const data=JSON.parse(readFileSync(base+"data/history-manifest.json","utf8"));
const sources=JSON.parse(readFileSync(base+"data/sources.json","utf8"));
const old=JSON.parse(readFileSync(base+"data/manifest.json","utf8"));
assert.equal(data.mode,"upstream-git-blame-surviving-lines");
assert.equal(data.sourceSHA,"500158f732419217507c7656904b8e6aa1bcc0d6");
assert.equal(data.events.length,10580);
assert.equal(data.startMinute,1,"Simulated replay must start D01 00:01");
assert.equal(data.files.length,132);
assert.equal(data.metrics.sourceLines,8957);
assert.equal(data.metrics.historyAttributedLines,8957);
assert.equal(data.metrics.deletionSteps,0);
assert.equal(Object.keys(sources).length,118);
assert.equal(old.metrics.sourceLines,data.metrics.sourceLines);
const commits=data.phases;
assert(commits.length>0);
assert.equal(data.metrics.realCommits,commits.length);
let total=0,nonascending=0;
for(const f of data.files){
 if(f.kind!=="text")continue;
 const expected=sources[f.path]||[];
 assert.equal(f.lineSteps.length,expected.length,"line count "+f.path);
 assert.equal(f.chronologicalSteps.length,expected.length,"time index "+f.path);
 assert.deepEqual([...f.lineSteps].sort((a,b)=>a-b),f.chronologicalSteps);
 for(let i=0;i<f.lineSteps.length;i++){
  const step=f.lineSteps[i],ev=data.events[step];
  assert.equal(ev.kind,"add");
  assert.equal(ev.file,f.path);
  assert.equal(ev.line,i);
  assert.match(ev.upstreamSHA,/^[0-9a-f]{40}$/);
  if(i>0&&step<f.lineSteps[i-1])nonascending++;
  total++;
 }
}
assert.equal(total,8957);
assert.equal(data.events.filter(e=>e.kind==="add").length,total);
assert(!data.events.some(e=>["delete","strike","remove"].includes(e.kind)));
assert.equal(commits.reduce((sum,p)=>sum+p.totalLines,0),total);
const sorted=[...commits].sort((a,b)=>a.totalLines-b.totalLines||a.id-b.id);
const lines=[
"# Spring Petclinic — Real Git History (Surviving Source Lines)","",
"**Based on actual upstream Git commit SHAs and \`git blame\` for the pinned snapshot.**",
"These are NOT the developers' keystrokes or terminal logs. Historical deleted lines are excluded.",
"",
"Source revision: "+data.sourceSHA,
"",
"Audited: "+data.events.length.toLocaleString()+" simulated minute actions; "+
 total.toLocaleString()+" attributed surviving source lines; "+data.files.length+
 " files; "+commits.length+" real upstream commits represented; zero replay deletions.",
"",
"**Coverage:** 100% of final source lines mapped to upstream Git blame commits. "+
"This is NOT a measured percentage of actual human coding behavior.",
"",
"| Commit | Surviving lines | Files changed | Actual commit subject |",
"|---:|---:|---:|---|"
];
for(const p of sorted){
 lines.push("| [C"+String(p.id).padStart(4,"0")+"](https://sabareeshrao.github.io/Gradstudio-Version-2.0/github-timestamps/petclinic/?commit="+p.id+") | "+p.totalLines+
 " | "+p.filesChanged+" | "+p.title.replaceAll("|","/")+" ([upstream]("+p.url+")) |");
}
lines.push("","## Auditing notes","",
"- Commit sequence follows the repository's upstream ancestry, not invented file-by-file commits.",
"- Files can be revisited and lines can appear out of final-file line order.",
"- Displayed per-commit counts are surviving final lines attributed by Git blame, **not all added lines in the original patch**.",
"- Intra-commit typing order, commands, clock and editor saves are reconstructed.",
"- Reordered final-line indices in the same source file: "+nonascending,"");
writeFileSync(base+"COMMIT_TABLE.md",lines.join("\n"),"utf8");
const stamp=i=>{
 const n=data.startMinute+i;
 return "D"+String(1+Math.floor(n/1440)).padStart(2,"0")+" "+
 String(Math.floor((n%1440)/60)).padStart(2,"0")+":"+String(n%60).padStart(2,"0");
};
const addedLines=data.events.flatMap((e,index)=>e.kind==="add"?[{
 step:index+1,timestamp:stamp(index),sha:e.upstreamSHA,commit:e.commit+1,
 file:e.file,line:e.line+1
}]:[]);
const detail={sourceSHA:data.sourceSHA,mode:data.mode,metrics:data.metrics,
 commits:commits.map(p=>({id:p.id,sha:p.sha,url:p.url,date:p.date,title:p.title,
  firstStep:p.fromStep+1,lastStep:p.toStep+1,survivingLines:p.totalLines,
  filesChanged:p.filesChanged,changes:p.changes})),addedLines};
assert.equal(addedLines.length,total);
writeFileSync(base+"data/history-commits.json",JSON.stringify(detail),"utf8");
console.log("HISTORY TABLE AUDIT PASSED",{commits:commits.length,survivingLines:total,
 totalSteps:data.events.length,nonascending,attributionCoverage:100});


// Exact first 100 simulated minutes, organized by actual upstream commit and file.
// Source lines are quoted from the pinned source fixture, not generated by an LLM.
const first100=data.events.slice(0,100);
const summary=first100.reduce((o,e)=>(o[e.kind]=(o[e.kind]||0)+1,o),{});
const grouped=new Map();
first100.forEach((e,i)=>{
 const id=Number.isInteger(e.commit)?e.commit:-1;
 if(!grouped.has(id))grouped.set(id,{actions:[],files:new Map()});
 const g=grouped.get(id);g.actions.push({event:e,step:i});
 if(e.kind==="add"){
  if(!g.files.has(e.file))g.files.set(e.file,[]);
  g.files.get(e.file).push({event:e,step:i});
 }
});
const out=[
 "# Spring Petclinic — First 100 Minutes", "",
 "**"+stamp(0)+"–"+stamp(99)+" (inclusive).** These are simulated minute markers. Git SHAs and surviving code lines are evidence-backed; terminal and typing actions are reconstructed.",
 "",
 "Source SHA: "+data.sourceSHA,
 "",
 "| Event type | Count |","|---|---:|",
 ...Object.entries(summary).map(([kind,count])=>"| "+kind+" | "+count+" |"),
 "",
 "## Features and exact code lines"
];
let groupN=0;
for(const [id,g] of grouped){
 groupN++;
 const phase=id>=0?commits[id]:null;
 out.push("","### "+groupN+". "+(phase?phase.title:"Project setup"),
  phase?"Real upstream commit: ["+phase.sha.slice(0,12)+"]("+phase.url+")":"No upstream commit assigned to setup");
 for(const [path,arr] of g.files){
  const first=arr[0].step,last=arr.at(-1).step;
  out.push("","#### "+path+" — "+arr.length+" attributed code lines · "+
      stamp(first)+"–"+stamp(last),"","~~~"+(data.files.find(f=>f.path===path)?.language||"text"));
  for(const {event:e,step} of arr){
   // Explicit time/line labels are outside source text to avoid contaminating code.
   const code=(sources[path]||[])[e.line];
   assert.equal(typeof code,"string","Missing source line "+path+":"+e.line);
   out.push(code);
  }
  out.push("~~~","");
  out.push("Code-line map:");
  for(const {event:e,step} of arr){
   out.push("- "+stamp(step)+" — L"+(e.line+1)+": "+JSON.stringify(sources[path][e.line]));
  }
 }
 const operations=g.actions.filter(x=>x.event.kind!=="add");
 if(operations.length){
  out.push("","#### Development actions ("+operations.length+")");
  for(const {event:e,step} of operations){
   out.push("- "+stamp(step)+" — "+e.kind+": "+(e.command?"\`"+e.command.replaceAll("\`","\\\`")+"\`":e.label||"Editor action"));
  }
 }
}
out.push("","## Verification",
 "- Exactly 100 timeline actions, from global step 1 through step 100.",
 "- All source lines are printed with the corresponding pinned final-file line numbers.",
 "- Git commit SHAs are genuine upstream provenance; intra-commit typing order is reconstructed.",
 "- No assumption is made that a file was runnable before all dependencies were present.","");
writeFileSync(base+"FIRST_100_MINUTES.md",out.join("\n"),"utf8");
console.log("FIRST 100 MINUTES",summary,"groups",grouped.size);


// Subsequent 100-minute report: real SHA provenance, reconstructed minute events.
{
 const start=100,stop=200;
 const slice=data.events.slice(start,stop);
 assert.equal(slice.length,100);
 const counts=slice.reduce((a,e)=>(a[e.kind]=(a[e.kind]||0)+1,a),{});
 const groups=new Map();
 slice.forEach((event,offset)=>{
  const index=start+offset,commit=Number.isInteger(event.commit)?event.commit:-1;
  if(!groups.has(commit))groups.set(commit,{operations:[],files:new Map()});
  const group=groups.get(commit);
  if(event.kind==="add"){
   if(!group.files.has(event.file))group.files.set(event.file,[]);
   group.files.get(event.file).push({event,index});
  }else group.operations.push({event,index});
 });
 const result=[
  "# Spring Petclinic — Minutes 101–200","",
  "**"+stamp(start)+"–"+stamp(stop-1)+" (inclusive)** · Steps "+(start+1)+"–"+stop+".",
  "",
  "This report uses the pinned source and Git blame evidence. Minute timestamps, typing order, and shell commands are reconstructed.",
  "",
  "| Event kind | Count |","|---|---:|",
  ...Object.entries(counts).map(([kind,n])=>"| "+kind+" | "+n+" |"),
  "",
  "## Feature additions, grouped by upstream commit and file"
 ];
 for(const [id,group] of groups){
  const commit=id<0?null:commits[id];
  result.push("","## "+(commit?commit.title:"Repository setup"),
   commit?"Upstream Git commit: ["+commit.sha.slice(0,12)+"]("+commit.url+")":"No upstream commit for initialization");
  for(const [path,lines] of group.files){
   result.push("","### "+path+" · "+lines.length+" surviving code lines · "+stamp(lines[0].index)+"–"+stamp(lines.at(-1).index),"");
   const lang=data.files.find(f=>f.path===path)?.language||"text";
   result.push("~~~"+lang);
   for(const {event} of lines){
    const code=sources[path]?.[event.line];
    assert.equal(typeof code,"string","Missing source line "+path+":"+event.line);
    result.push(code);
   }
   result.push("~~~","","Line-by-line timestamps:");
   for(const {event,index} of lines)result.push("- "+stamp(index)+" · L"+(event.line+1)+": "+JSON.stringify(sources[path][event.line]));
  }
  if(group.operations.length){
   result.push("","### Terminal and editor actions");
   for(const {event,index} of group.operations){
    const command=event.command ? " \`"+event.command.replaceAll("\`","\\\`")+"\`" : event.label||"Save editor buffer";
    result.push("- "+stamp(index)+" · "+event.kind+": "+command);
   }
  }
 }
 result.push("","## Source and timing audit","",
 "- Steps 101–200 only; exactly 100 event slots.",
 "- File content is transcribed from the pinned final source snapshot.",
 "- Real Git commit SHA provenance; reconstructed code-writing order and terminal actions.",
 "- No guarantee that this partial replay represents a compilable project at these timestamps.","");
 writeFileSync(base+"SECOND_100_MINUTES.md",result.join("\n"),"utf8");
 console.log("MINUTES 101–200 REPORT",counts,"groups",groups.size);
}
